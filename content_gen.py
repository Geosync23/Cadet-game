#!/usr/bin/env python3
"""content_gen.py: bakes the plain text files under content/ into the game's generated blocks.

    python3 content_gen.py [GAME.html] [--check]

Reads content/ (see content/README.md, the writers' guide) and rewrites, in the game file (default
starship-cadet.html), everything between these markers, which sit in section 22 (LINES):

    // ---- BEGIN LINES ...       // ---- END LINES ----        VOICE_TEMPLATES, VOICE, LINES, CONVOS
    // ---- BEGIN MEETINGS ...    // ---- END MEETINGS ----     MEETINGS_BAKED (merged into MEETING_SCRIPTS)
    // ---- BEGIN TRADITIONS ...  // ---- END TRADITIONS ----   TRADITIONS (read by section 18's loader)

Nobody hand-edits a generated block. Running it again with no changes to content/ gives byte-identical output.
--check changes nothing and exits 1 if the game file is out of date. The shapes are the social plan's Part 9
(plans/social-deep-plan.md); the condition words are the frozen vocabulary in COND_KEYS below (and the README).
Syntax errors stop the bake with the file and line; style (lengths, names, tone, coverage) is lines_check.py's job.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
CONTENT = os.path.join(ROOT, 'content')

TIERS = {'stranger': 0, 'acquaintance': 1, 'colleague': 2, 'friend': 3, 'close': 4}
# the frozen condition vocabulary (wave 1, agreed with the social system designer): key -> who answers it
COND_KEYS = {
    # social: section 20's pure queries
    'mem': 'social', 'told': 'social', 'warmth': 'social', 'aff': 'social', 'bond': 'social', 'mood': 'social',
    'beat': 'social', 'news': 'social', 'rep': 'social', 'ship.work': 'social', 'ship.kindness': 'social',
    'ship.spirit': 'social', 'you': 'social', 'cue': 'social', 'flag': 'social', 'week1': 'social',
    # the dialogue engine's (section 22)
    'time': 'lines', 'weekday': 'lines', 'season': 'lines', 'place': 'lines', 'deck': 'lines', 'event': 'lines',
    'trad': 'lines', 'dept': 'lines', 'rank': 'lines', 'trait': 'lines', 'habit': 'lines', 'act': 'lines',
    'birthday': 'lines', 'pair': 'lines', 'topic': 'lines',
}
NUM_KEYS = ('w', 'odds')                     # numbers, not conditions: a weight, and a seeded chance
TONES = ('light', 'funny', 'warm', 'serious')
VOICE_LISTS = ('cares', 'jokes', 'loves', 'likes', 'invites', 'avoid')
VOICE_WORDS = ('hi', 'bye', 'yes', 'thanks', 'wow', 'sigh')
VOICE_SCALARS = ('tpl', 'talk', 'needs', 'openness', 'joy', 'thread', 'keepsake')
MARK = '(generated by content_gen.py from content/: never hand-edit; edit content/ and re-run it)'


class GenError(Exception):
    pass


def line_id(path, kind, text):
    """A line's id: a short hash of its file, kind and text (FNV-1a, base 36), stable across runs."""
    h = 0x811c9dc5
    for b in (path + '|' + kind + '|' + text).encode('utf-8'):
        h = ((h ^ b) * 0x01000193) & 0xffffffff
    s, a = '', '0123456789abcdefghijklmnopqrstuvwxyz'
    while True:
        s = a[h % 36] + s
        h //= 36
        if not h:
            return s


def parse_conds(text, where):
    """'tier>=friend time:morning !flag:met.calder w:2' -> { tier: [3, 4], time: 'morning', not: { flag: ... }, w: 2 }"""
    c = {}
    for tok in text.split():
        neg = tok.startswith('!')
        if neg:
            tok = tok[1:]
        dst = c.setdefault('not', {}) if neg else c
        m = re.fullmatch(r'tier(>=|<=|=|>|<)(\w+)', tok)
        if m:
            op, v = m.groups()
            n = TIERS.get(v, int(v) if v.isdigit() else None)
            if n is None or not 0 <= n <= 4:
                raise GenError(f'{where}: unknown tier "{v}" (0-4 or {", ".join(TIERS)})')
            lo, hi = {'=': (n, n), '>=': (n, 4), '<=': (0, n), '>': (n + 1, 4), '<': (0, n - 1)}[op]
            if lo > hi:
                raise GenError(f'{where}: "{tok}" can never hold')
            old = dst.get('tier', [0, 4])
            dst['tier'] = [max(lo, old[0]), min(hi, old[1])]
            continue
        if ':' not in tok:
            raise GenError(f'{where}: "{tok}" is not a condition (key:value or tier>=...)')
        k, v = tok.split(':', 1)
        if k in NUM_KEYS and not neg:
            try:
                c[k] = float(v) if '.' in v else int(v)
            except ValueError:
                raise GenError(f'{where}: {k} needs a number, got "{v}"')
            continue
        if k not in COND_KEYS:
            raise GenError(f'{where}: unknown condition "{k}" (see content/README.md, "Conditions")')
        if not v:
            raise GenError(f'{where}: "{tok}" has no value')
        if k in dst:                              # the same key twice: all must hold
            dst[k] = (dst[k] if isinstance(dst[k], list) else [dst[k]]) + [v]
        else:
            dst[k] = v
    return c


def merge_conds(a, b):
    out = json.loads(json.dumps(a))
    for k, v in b.items():
        if k == 'not':
            out['not'] = merge_conds(out.get('not', {}), v)
        elif k == 'tier' and 'tier' in out:
            out['tier'] = [max(v[0], out['tier'][0]), min(v[1], out['tier'][1])]
        elif k in out and k not in NUM_KEYS:
            out[k] = (out[k] if isinstance(out[k], list) else [out[k]]) + (v if isinstance(v, list) else [v])
        else:
            out[k] = v
    return out


def split_tone(text, where):
    tone = 'light'
    m = re.search(r'\s+#(\w+)\s*$', text)
    if m:
        if m.group(1) not in TONES:
            raise GenError(f'{where}: unknown tone #{m.group(1)} ({", ".join("#" + t for t in TONES)})')
        tone, text = m.group(1), text[:m.start()]
    return text.strip(), tone


def entry(path, kind, text, tone, conds, extra=None):
    e = {'text': text, 'id': line_id(path, kind, text)}
    if tone != 'light':
        e['tone'] = tone
    for k in NUM_KEYS:
        if k in conds:
            e[k] = conds[k]
    for k in sorted(x for x in conds if x not in NUM_KEYS and x != 'not'):
        e[k] = conds[k]
    if conds.get('not'):
        e['not'] = {k: conds['not'][k] for k in sorted(conds['not'])}
    if extra:
        e.update(extra)
    return e


def read_lines(path):
    """The file's lines with their numbers, comments (// at the start) dropped, right-trimmed."""
    with open(path, encoding='utf-8') as f:
        raw = f.read()
    if '\t' in raw:
        raise GenError(f'{path}: tabs; use spaces')
    out = []
    for i, l in enumerate(raw.split('\n'), 1):
        l = l.rstrip()
        if l.lstrip().startswith('//'):
            continue
        out.append((i, l))
    return out


def header(lines, path):
    for i, l in lines:
        if l.strip():
            if not l.startswith('@'):
                raise GenError(f'{path}:{i}: the first line must be an @header (@crew, @bank, @template, ...)')
            return l[1:].split()
    raise GenError(f'{path}: empty file')


def parse_lines_file(path, rel, out):
    lines = read_lines(path)
    hd = header(lines, path)
    what, args = hd[0], hd[1:]
    base, extra, kind, conds = {}, None, None, {}
    if what == 'crew':
        if len(args) != 1:
            raise GenError(f'{path}: @crew takes one crew id')
        target = out['VOICE'].setdefault(args[0], {}).setdefault('lines', {})
    elif what == 'template':
        if len(args) != 1:
            raise GenError(f'{path}: @template takes one template name')
        target = out['VOICE_TEMPLATES'].setdefault(args[0], {}).setdefault('lines', {})
    elif what == 'bank':
        old = 'old' in args
        base = parse_conds(' '.join(a for a in args if a not in ('all', 'old')), path)
        target, extra = out['LINES'], ({'old': 1} if old else None)
    elif what == 'reactions':
        if len(args) != 1:
            raise GenError(f'{path}: @reactions takes one cue kind (repair.lamp, tradition.quiz, ...)')
        base, target, kind = {'cue': args[0]}, out['LINES'], 'cue'
    elif what == 'overheard':
        if len(args) != 1:
            raise GenError(f'{path}: @overheard takes one topic')
        return parse_overheard(lines, path, rel, args[0], out)
    else:
        raise GenError(f'{path}: unknown header @{what} in a .lines file')
    seen = set()
    for i, l in lines:
        where = f'{path}:{i}'
        s = l.strip()
        if not s or s.startswith('@'):
            continue
        if s.startswith('=='):
            kind, conds = s[2:].strip(), {}
            if not re.fullmatch(r'[a-z][a-zA-Z0-9]*(\.[a-zA-Z0-9-]+)*', kind):
                raise GenError(f'{where}: "{kind}" is not a line kind')
            continue
        if s.startswith('?'):
            conds = parse_conds(s[1:], where)
            continue
        if s.startswith('- '):
            if not kind:
                raise GenError(f'{where}: a line before any "== kind"')
            text, tone = split_tone(s[2:], where)
            if not text:
                raise GenError(f'{where}: empty line')
            if (kind, text) in seen:
                raise GenError(f'{where}: the same line twice in one kind')
            seen.add((kind, text))
            target.setdefault(kind, []).append(entry(rel, kind, text, tone, merge_conds(base, conds), extra))
            continue
        raise GenError(f'{where}: not understood (lines start with "- ", conditions with "? ", kinds with "== ")')


def parse_overheard(lines, path, rel, topic, out):
    conds, cur, n = {}, None, 0

    def close():
        nonlocal cur
        if cur:
            if len(cur['lines']) < 2:
                raise GenError(f'{path}: a conversation needs at least two lines (near line {cur["at"]})')
            text = '\n'.join(x['who'] + ':' + x['text'] for x in cur['lines'])
            c = merge_conds({'topic': topic}, cur['conds'])
            e = {'id': line_id(rel, 'overheard', text)}
            if cur['tone'] != 'light':
                e['tone'] = cur['tone']
            for k in NUM_KEYS:
                if k in c:
                    e[k] = c[k]
            for k in sorted(x for x in c if x not in NUM_KEYS and x != 'not'):
                e[k] = c[k]
            if c.get('not'):
                e['not'] = {k: c['not'][k] for k in sorted(c['not'])}
            e['lines'] = cur['lines']
            out['CONVOS'].append(e)
        cur = None

    for i, l in lines:
        where = f'{path}:{i}'
        if l.startswith('@'):
            continue
        s = l.strip()
        if not s or s == '---':
            close()
            continue
        if s.startswith('=='):
            close()
            if s[2:].strip() != 'overheard':
                raise GenError(f'{where}: an overheard file has only "== overheard" sections')
            continue
        if s.startswith('?'):
            close()
            conds = parse_conds(s[1:], where)
            continue
        m = re.fullmatch(r'([ABC]):\s*(.+)', s)
        if not m:
            raise GenError(f'{where}: overheard lines start with "A:", "B:" or "C:"')
        text, tone = split_tone(m.group(2), where)
        if cur is None:
            cur = {'conds': conds, 'lines': [], 'tone': 'light', 'at': i}
        if tone != 'light':
            cur['tone'] = tone
        cur['lines'].append({'who': m.group(1), 'text': text})
    close()


def parse_voice_file(path, rel, out):
    lines = read_lines(path)
    hd = header(lines, path)
    if hd[0] == 'voice' and len(hd) == 2:
        card = out['VOICE'].setdefault(hd[1], {})
    elif hd[0] == 'template' and len(hd) == 2:
        card = out['VOICE_TEMPLATES'].setdefault(hd[1], {})
    else:
        raise GenError(f'{path}: a .voice file starts with "@voice <crewId>" or "@template <name>"')
    for i, l in lines:
        where = f'{path}:{i}'
        if l.startswith('@'):
            continue
        if not l.strip() or l.startswith('@'):
            continue
        m = re.fullmatch(r'([a-z]+):\s*(.*)', l.strip())
        if not m:
            raise GenError(f'{where}: voice card lines are "key: value"')
        k, v = m.groups()
        items = [x.strip() for x in v.split('|')]
        if k in VOICE_SCALARS:
            card[k] = v.strip()
        elif k in VOICE_LISTS:
            card[k] = items
        elif k in VOICE_WORDS:
            card.setdefault('words', {})[k] = items
        elif k == 'nick':
            if len(items) != 5:
                raise GenError(f'{where}: nick needs five values, one per tier (- for "use {{me}}")')
            card.setdefault('words', {})['nick'] = [None if x == '-' else x for x in items]
        else:
            raise GenError(f'{where}: unknown voice card field "{k}"')


def parse_meeting(path, rel, out):
    """@meeting <id>; title/from/gist/notify: fields; == lines; 'who: text [pose]' or 'who > to: text';
    '? choice' then '* reply text  rel:calder+2,tech2+1 job:x flavour:listen mem:k flag:k favour:k' with an
    indented 'who: text [pose]' under each choice as its reply."""
    lines = read_lines(path)
    hd = header(lines, path)
    if hd[0] != 'meeting' or len(hd) != 2:
        raise GenError(f'{path}: a .meet file starts with "@meeting <id>"')
    sc, body, choice = {}, None, None
    for i, l in lines:
        where = f'{path}:{i}'
        if l.startswith('@'):
            continue
        s = l.strip()
        if not s:
            continue
        if body is None:
            if s == '== lines':
                body = []
                continue
            m = re.fullmatch(r'(title|from|gist|notify):\s*(.+)', s)
            if not m:
                raise GenError(f'{where}: before "== lines" only title:, from:, gist:, notify:')
            sc[m.group(1)] = m.group(2)
            continue
        if s == '? choice':
            choice = {'choice': []}
            body.append(choice)
            continue
        if s.startswith('* '):
            if choice is None:
                raise GenError(f'{where}: a "* choice" outside "? choice"')
            parts = re.split(r'\s+(?=(?:rel|job|flavour|mem|flag|favour):)', s[2:].strip())
            ch = {'text': parts[0]}
            for p in parts[1:]:
                k, v = p.split(':', 1)
                if k == 'rel':
                    ch['rel'] = {}
                    for r in v.split(','):
                        m = re.fullmatch(r'([\w-]+)([+-]\d+)', r)
                        if not m:
                            raise GenError(f'{where}: rel is like calder+2,tech2+1')
                        ch['rel'][m.group(1)] = int(m.group(2))
                else:
                    ch[k] = v
            choice['choice'].append(ch)
            continue
        m = re.fullmatch(r'([\w-]+)(?:\s*>\s*([\w-]+))?:\s*(.+?)(?:\s+\[(\w+)\])?', s)
        if not m:
            raise GenError(f'{where}: meeting lines are "who: text [pose]"')
        ln = {'who': m.group(1), 'text': m.group(3)}
        if m.group(4):
            ln['pose'] = m.group(4)
        if m.group(2):
            ln['to'] = m.group(2)
        if l.startswith(' ') and choice is not None and choice['choice']:
            choice['choice'][-1]['reply'] = ln
            continue
        choice = None
        body.append(ln)
    if not body:
        raise GenError(f'{path}: no "== lines"')
    sc['lines'] = body
    out['MEETINGS_BAKED'][hd[1]] = sc


def parse_tradition(path, rel, out):
    """@tradition <id>; 'key: value' fields (the traditions engineer reads them: when, len, where, who, anim, host,
    ties, mail, thanks, ...); then '== section' and '- text  #tone' lines (tap, chatter, ...)."""
    lines = read_lines(path)
    hd = header(lines, path)
    if hd[0] != 'tradition' or len(hd) != 2:
        raise GenError(f'{path}: a .trad file starts with "@tradition <id>"')
    tr, sec, conds = {}, None, {}
    for i, l in lines:
        where = f'{path}:{i}'
        if l.startswith('@'):
            continue
        s = l.strip()
        if not s:
            continue
        if s.startswith('=='):
            sec, conds = s[2:].strip(), {}
            tr.setdefault('text', {}).setdefault(sec, [])
            continue
        if sec is None:
            m = re.fullmatch(r'([a-z][a-zA-Z0-9]*):\s*(.+)', s)
            if not m:
                raise GenError(f'{where}: tradition fields are "key: value"')
            tr[m.group(1)] = m.group(2)
            continue
        if s.startswith('?'):
            conds = parse_conds(s[1:], where)
            continue
        if not s.startswith('- '):
            raise GenError(f'{where}: lines start with "- "')
        text, tone = split_tone(s[2:], where)
        tr['text'][sec].append(entry(rel, 'trad.' + hd[1] + '.' + sec, text, tone, conds))
    out['TRADITIONS'][hd[1]] = tr


def bake():
    out = {'VOICE_TEMPLATES': {}, 'VOICE': {}, 'LINES': {}, 'CONVOS': [], 'MEETINGS_BAKED': {}, 'TRADITIONS': {}}
    files = []
    for d, _, fs in os.walk(CONTENT):
        for f in fs:
            files.append(os.path.relpath(os.path.join(d, f), CONTENT).replace(os.sep, '/'))
    for rel in sorted(files):
        path = os.path.join(CONTENT, rel)
        ext = rel.rsplit('.', 1)[-1] if '.' in rel else ''
        if ext == 'lines':
            parse_lines_file(path, rel, out)
        elif ext == 'voice':
            parse_voice_file(path, rel, out)
        elif ext == 'meet':
            parse_meeting(path, rel, out)
        elif ext == 'trad':
            parse_tradition(path, rel, out)
    ids = {}
    for kind, es in out['LINES'].items():
        for e in es:
            if e['id'] in ids:
                raise GenError(f'two lines share id {e["id"]} ({kind}: "{e["text"]}"); reword one')
            ids[e['id']] = 1
    return out


def js(v):
    return json.dumps(v, ensure_ascii=False, separators=(', ', ': '))


def js_obj_of_lists(name, d):
    """const NAME = { "kind": [ one entry a line ] } (sorted keys)"""
    o = [f'const {name} = {{']
    for k in sorted(d):
        o.append(f'  {js(k)}: [')
        o += [f'    {js(e)},' for e in d[k]]
        o.append('  ],')
    o.append('};')
    return o


def js_cards(name, d):
    o = [f'const {name} = {{']
    for k in sorted(d):
        card = d[k]
        o.append(f'  {js(k)}: {{')
        for f in sorted(x for x in card if x != 'lines'):
            o.append(f'    {js(f)}: {js(card[f])},')
        if 'lines' in card:
            o.append('    "lines": {')
            for kind in sorted(card['lines']):
                o.append(f'      {js(kind)}: [')
                o += [f'        {js(e)},' for e in card['lines'][kind]]
                o.append('      ],')
            o.append('    },')
        o.append('  },')
    o.append('};')
    return o


def blocks(out):
    lines = js_cards('VOICE_TEMPLATES', out['VOICE_TEMPLATES']) + js_cards('VOICE', out['VOICE']) \
        + js_obj_of_lists('LINES', out['LINES']) + ['const CONVOS = ['] + [f'  {js(c)},' for c in out['CONVOS']] + ['];']
    meet = ['const MEETINGS_BAKED = {'] + [f'  {js(k)}: {js(out["MEETINGS_BAKED"][k])},' for k in sorted(out['MEETINGS_BAKED'])] + ['};']
    trad = ['const TRADITIONS = {'] + [f'  {js(k)}: {js(out["TRADITIONS"][k])},' for k in sorted(out['TRADITIONS'])] + ['};']
    return {'LINES': lines, 'MEETINGS': meet, 'TRADITIONS': trad}


def splice(html, name, body):
    b = re.search(r'^// ---- BEGIN ' + name + r' .*$', html, re.M)
    e = re.search(r'^// ---- END ' + name + r' ----$', html, re.M)
    if not b or not e or e.start() < b.end():
        raise GenError(f'the game file has no "// ---- BEGIN {name} ..." / "// ---- END {name} ----" markers')
    return html[:b.start()] + f'// ---- BEGIN {name} {MARK} ----\n' + '\n'.join(body) + '\n' + html[e.start():]


def main(argv):
    check = '--check' in argv
    args = [a for a in argv if not a.startswith('--')]
    game = args[0] if args else os.path.join(ROOT, 'starship-cadet.html')
    try:
        out = bake()
        with open(game, encoding='utf-8') as f:
            html = f.read()
        new = html
        for name, body in blocks(out).items():
            new = splice(new, name, body)
    except GenError as e:
        print('content_gen: ' + str(e))
        return 2
    n = sum(len(v) for v in out['LINES'].values()) + sum(len(es) for c in list(out['VOICE'].values()) + list(out['VOICE_TEMPLATES'].values()) for es in c.get('lines', {}).values())
    summary = (f'{n} lines, {len(out["VOICE"])} voice cards, {len(out["VOICE_TEMPLATES"])} templates, {len(out["CONVOS"])} conversations, '
               f'{len(out["MEETINGS_BAKED"])} meetings, {len(out["TRADITIONS"])} traditions')
    if check:
        print(('up to date: ' if new == html else 'OUT OF DATE: ') + summary)
        return 0 if new == html else 1
    if new != html:
        with open(game, 'w', encoding='utf-8') as f:
            f.write(new)
    print(('baked: ' if new != html else 'no change: ') + summary)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
